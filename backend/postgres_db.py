"""PostgreSQL adapter for the existing SQLite-shaped application queries.

The same services work with Neon (DATABASE_URL) and local SQLite (DATABASE_PATH).
All user values continue to go through bound parameters.
"""
from __future__ import annotations

import threading
from contextlib import contextmanager
from typing import Any, Iterator

import psycopg
from psycopg.rows import dict_row

from .db import SCHEMA_SQL, row_to_dict


def _postgres_sql(sql: str) -> str:
    # This application uses SQLite's qmark bound-parameter convention.
    return sql.replace("?", "%s")


class PostgresDatabase:
    is_postgres = True

    def __init__(self, database_url: str):
        self.conn = psycopg.connect(
            database_url,
            connect_timeout=10,
            autocommit=True,
            row_factory=dict_row,
            prepare_threshold=None,
        )
        self._lock = threading.RLock()
        self._migrated = False

    def close(self) -> None:
        with self._lock:
            self.conn.close()

    @contextmanager
    def immediate_tx(self) -> Iterator[None]:
        # PostgreSQL transactions guarantee that multi-table writes either
        # all commit or all roll back. The lock serializes this connection's use.
        with self._lock:
            with self.conn.transaction():
                yield

    @contextmanager
    def seed_lock(self) -> Iterator[None]:
        # Serialize startup seeding across Vercel worker instances.
        with self._lock:
            self.conn.execute("SELECT pg_advisory_lock(60268421)")
            try:
                yield
            finally:
                self.conn.execute("SELECT pg_advisory_unlock(60268421)")

    def execute(self, sql: str, params: tuple[Any, ...] | list[Any] = ()) -> Any:
        with self._lock:
            return self.conn.execute(_postgres_sql(sql), params)

    def fetch_one(self, sql: str, params: tuple[Any, ...] | list[Any] = ()) -> dict[str, Any] | None:
        with self._lock:
            with self.conn.execute(_postgres_sql(sql), params) as cur:
                return row_to_dict(cur.fetchone())

    def fetch_all(self, sql: str, params: tuple[Any, ...] | list[Any] = ()) -> list[dict[str, Any]]:
        with self._lock:
            with self.conn.execute(_postgres_sql(sql), params) as cur:
                return [row_to_dict(row) for row in cur.fetchall()]

    def insert_returning(self, sql: str, params: tuple[Any, ...] | list[Any] = ()) -> dict[str, Any]:
        row = self.fetch_one(sql, params)
        if row is None:
            raise RuntimeError("INSERT RETURNING did not yield a row")
        return row

    def exec_script(self, script: str) -> None:
        schema = script.replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        )
        with self._lock:
            with self.conn.transaction():
                for statement in schema.split(";"):
                    if statement.strip():
                        self.conn.execute(statement)
